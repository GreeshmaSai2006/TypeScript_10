export function sumValues(num1: number, num2: number): number {
    return num1 + num2;
}

export function differenceValues(num1: number, num2: number): number {
    return num1 - num2;
}

export function productValues(num1: number, num2: number): number {
    return num1 * num2;
}

export function quotientValues(num1: number, num2: number): number {
    return num1 / num2;
}